// Writes lib/data/globe-land.ts: a 720x360 (0.5 degree) land/sea bitmap, base64, used by the homepage globe
// to place its dots. Natural Earth land (public domain) via the world-atlas package. Usage:
//   node scripts/build-globe-land.mjs path/to/world-atlas/land-110m.json
// Needs topojson-client and d3-geo resolvable from the working directory (install them in a scratch folder).
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(process.cwd() + "/")
const { feature } = require("topojson-client")
const { geoContains } = require("d3-geo")

const input = process.argv[2]
if (!input) {
  console.error("Usage: node scripts/build-globe-land.mjs path/to/land-110m.json")
  process.exit(1)
}
const topo = JSON.parse(readFileSync(input, "utf8"))
const land = feature(topo, topo.objects.land)

const W = 720
const H = 360
const bits = new Uint8Array((W * H) / 8)
let count = 0
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5) / 2
  for (let x = 0; x < W; x++) {
    const lng = -180 + (x + 0.5) / 2
    if (geoContains(land, [lng, lat])) {
      const i = y * W + x
      bits[i >> 3] |= 1 << (i & 7)
      count++
    }
  }
}
const b64 = Buffer.from(bits).toString("base64")
writeFileSync(
  new URL("../lib/data/globe-land.ts", import.meta.url),
  `// Generated by scripts/build-globe-land.mjs - do not edit.\n// ${W}x${H} bitmap, row-major from 90N/180W, 1 bit per 0.5 degree cell, LSB first. 1 = land.\nexport const LAND_WIDTH = ${W}\nexport const LAND_HEIGHT = ${H}\nexport const LAND_BITMAP = "${b64}"\n`,
)
console.log("land cells", count, "of", W * H, "->", b64.length, "chars")
